import { useState } from 'react';
import { Page } from '../components/Layout';
import { DataTable } from '../components/DataTable';
import { Field, ProcedureForm } from '../components/ProcedureForm';
import { Badge, Card, PageHeader, stateTone, Tile } from '../components/ui';
import { atLeast } from '../lib/api';
import { useAuth } from '../lib/auth';
import { useView } from '../lib/hooks';
import { useProject } from '../lib/project';
import { dateTime, money, num, shortDate } from '../lib/format';

interface Invoice { invoice_id: number; project_id: number; project_name: string; period_start: string; period_end: string; total: string; status: string; paid: string }
interface Line { invoice_id: number; line_no: number; resource_name: string; units: string; unit_price: string; amount: string }
interface Cost { project_id: number; project_name: string; cost_mtd: string }
interface Cycle { cycle_id: number; period_start: string; period_end: string }
interface Price { plan_id: number; resource_type: string; unit_price: string; unit: string; effective_from: string; effective_to: string | null }
interface Failure { failure_id: number; cycle_id: number; project_id: number; sqlstate: string; message: string; at: string }
interface Outcome { project_id: number; outcome: string; invoice_id: number | null; detail: string | null }

export function Billing() {
  const { projectId } = useProject();
  const { user } = useAuth();
  const p = projectId ? { project_id: projectId } : undefined;
  const [sel, setSel] = useState<number | null>(null);
  const [outcomes, setOutcomes] = useState<Outcome[] | null>(null);
  const invoices = useView<Invoice>('v_invoices', p);
  const lines = useView<Line>('v_invoice_lines', { invoice_id: sel ?? undefined }, { enabled: sel !== null });
  const cost = useView<Cost>('v_project_cost_mtd', p);
  const cycles = useView<Cycle>('v_billing_cycles');
  const prices = useView<Price>('v_pricing');
  const isAdmin = user && atLeast(user.role, 'admin');
  const failures = useView<Failure>('v_billing_failures', undefined, { enabled: !!isAdmin });
  const canPay = user && atLeast(user.role, 'manager');
  const chosen = invoices.data?.find((i) => i.invoice_id === sel);
  const outstanding = (invoices.data ?? []).filter((i) => i.status !== 'paid' && i.status !== 'void').reduce((a, i) => a + Number(i.total) - Number(i.paid), 0);

  const cycleFields: Field[] = [{ name: 'from', label: 'From', type: 'datetime' }, { name: 'to', label: 'To', type: 'datetime' }];
  const genFields: Field[] = [{ name: 'cycle_id', label: 'Billing cycle', type: 'select', options: (cycles.data ?? []).map((c) => ({ value: c.cycle_id, label: `#${c.cycle_id}: ${shortDate(c.period_start)} → ${shortDate(c.period_end)}` })), defaultValue: cycles.data?.[0]?.cycle_id }];

  return (
    <Page>
      <PageHeader title="Billing" subtitle="Invoices are generated by sp_generate_invoices; line prices are frozen at generation time" />
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Tile label="Month to date" value={money((cost.data ?? []).reduce((a, c) => a + Number(c.cost_mtd), 0))} sub="all visible projects" />
        <Tile label="Outstanding" value={money(outstanding)} tone={outstanding > 0 ? 'warn' : 'ok'} sub="issued minus payments" />
        <Tile label="Invoices" value={invoices.data?.length ?? '—'} sub={`${(invoices.data ?? []).filter((i) => i.status === 'paid').length} paid`} />
        <Tile label="Cycles" value={cycles.data?.length ?? '—'} />
      </div>

      <div className="mt-3 grid gap-3 lg:grid-cols-5">
        <Card title="Invoices" className="lg:col-span-3">
          <DataTable rows={invoices.data} loading={invoices.isLoading} rowKey={(i) => i.invoice_id} onRowClick={(i) => setSel(i.invoice_id)} pageSize={10} empty="No invoices"
            initialSort={{ key: 'period_start', dir: 'desc' }} columns={[
              { key: 'invoice_id', header: '#', align: 'right' },
              { key: 'project_name', header: 'Project' },
              { key: 'period_start', header: 'Period', render: (i: Invoice) => `${shortDate(i.period_start)} → ${shortDate(i.period_end)}` },
              { key: 'total', header: 'Total', align: 'right', value: (i: Invoice) => Number(i.total), render: (i: Invoice) => money(i.total) },
              { key: 'paid', header: 'Paid', align: 'right', value: (i: Invoice) => Number(i.paid), render: (i: Invoice) => money(i.paid) },
              { key: 'status', header: 'Status', render: (i: Invoice) => <Badge tone={stateTone(i.status)}>{i.status}</Badge> },
            ]} />
        </Card>
        <Card title={chosen ? `Invoice #${chosen.invoice_id} · ${chosen.project_name}` : 'Invoice detail'} className="lg:col-span-2">
          {!chosen ? <p className="p-3 text-xs text-muted">Select an invoice to see its line items.</p> : (
            <>
              <DataTable rows={lines.data} loading={lines.isLoading} pageSize={8} columns={[
                { key: 'line_no', header: 'Line', align: 'right' }, { key: 'resource_name', header: 'Resource' },
                { key: 'units', header: 'Units', align: 'right', render: (l: Line) => num(l.units, 2) },
                { key: 'unit_price', header: 'Unit price', align: 'right', render: (l: Line) => `$${num(l.unit_price, 4)}` },
                { key: 'amount', header: 'Amount', align: 'right', render: (l: Line) => money(l.amount) },
              ]} />
              <div className="flex justify-between border-t border-line px-3 py-2 text-sm font-medium"><span>Total</span><span>{money(chosen.total)}</span></div>
              {canPay && chosen.status !== 'paid' && chosen.status !== 'void' && (
                <div className="border-t border-line p-3">
                  <ProcedureForm key={chosen.invoice_id} inline procedure="sp_record_payment" fixed={{ invoice_id: chosen.invoice_id }} submitLabel="Record payment"
                    fields={[{ name: 'amount', label: `Amount (due ${money(Number(chosen.total) - Number(chosen.paid))})`, type: 'number', step: 0.01, min: 0.01, defaultValue: Number((Number(chosen.total) - Number(chosen.paid)).toFixed(2)) }]}
                    successMessage={() => 'Payment recorded'} />
                </div>
              )}
            </>
          )}
        </Card>
      </div>

      <div className="mt-3 grid gap-3 lg:grid-cols-2">
        <Card title="Month-to-date cost by project (v_project_cost_mtd)">
          <DataTable rows={cost.data} loading={cost.isLoading} columns={[
            { key: 'project_name', header: 'Project' },
            { key: 'cost_mtd', header: 'Cost', align: 'right', value: (c: Cost) => Number(c.cost_mtd), render: (c: Cost) => money(c.cost_mtd) },
          ]} />
        </Card>
        <Card title="Pricing plans (non-overlapping per type, EXCLUDE gist)">
          <DataTable rows={prices.data} loading={prices.isLoading} columns={[
            { key: 'resource_type', header: 'Type' },
            { key: 'unit_price', header: 'Price', align: 'right', render: (x: Price) => `$${num(x.unit_price, 6)} / ${x.unit}` },
            { key: 'effective_from', header: 'From', render: (x: Price) => shortDate(x.effective_from) },
            { key: 'effective_to', header: 'To', render: (x: Price) => (x.effective_to ? shortDate(x.effective_to) : <Badge tone="ok">current</Badge>) },
          ]} />
        </Card>
      </div>

      {isAdmin && (
        <div className="mt-3 grid gap-3 lg:grid-cols-2">
          <Card title="Create billing cycle"><div className="p-3"><ProcedureForm procedure="sp_create_billing_cycle" fields={cycleFields} submitLabel="Create cycle" successMessage={() => 'Cycle created'} /></div></Card>
          <Card title="Generate invoices (savepoint per project)">
            <div className="grid gap-3 p-3">
              <ProcedureForm key={cycles.data?.length} procedure="sp_generate_invoices" fields={genFields} submitLabel="Generate" onSuccess={(r) => setOutcomes((r.rows ?? []) as unknown as Outcome[])} />
              {outcomes && (
                <DataTable rows={outcomes} empty="No billable usage in this cycle" columns={[
                  { key: 'project_id', header: 'Project', align: 'right' },
                  { key: 'outcome', header: 'Outcome', render: (o: Outcome) => <Badge tone={o.outcome === 'invoiced' ? 'ok' : 'bad'}>{o.outcome}</Badge> },
                  { key: 'invoice_id', header: 'Invoice', align: 'right' }, { key: 'detail', header: 'Detail', className: 'whitespace-normal' },
                ]} />
              )}
            </div>
          </Card>
          <Card title="Billing failures log" className="lg:col-span-2">
            <DataTable rows={failures.data} loading={failures.isLoading} empty="No failures recorded" pageSize={5} columns={[
              { key: 'at', header: 'When', render: (f: Failure) => dateTime(f.at) }, { key: 'cycle_id', header: 'Cycle', align: 'right' }, { key: 'project_id', header: 'Project', align: 'right' },
              { key: 'sqlstate', header: 'SQLSTATE', className: 'mono' }, { key: 'message', header: 'Message', className: 'whitespace-normal' },
            ]} />
          </Card>
        </div>
      )}
    </Page>
  );
}
